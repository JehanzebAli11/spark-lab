"""Regenerate the README results block from results/*.json (CLAUDE.md: no hand-edited numbers).

    python -m labml.readme          # rewrite the block between the results markers
    python -m labml.readme --check  # exit 1 if the README is out of date (for CI)
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
START, END = "<!-- results:start (generated by python -m labml.readme) -->", "<!-- results:end -->"


def block() -> str:
    lc = json.loads((REPO / "results/log_classifier/metrics.json").read_text())
    dr = json.loads((REPO / "results/doctor/metrics.json").read_text())
    af = json.loads((REPO / "results/doctor/autofix.json").read_text())
    sp = lc["splits"]
    ht, hm = sp["heldout_test"]["model+threshold"], sp["heldout_test"]["model"]
    out = [START, "", "### Failure classifier (chaos logs, CPU)", "",
           f"TF-IDF + logistic regression, confidence threshold {lc['threshold']:.2f}. "
           "In-distribution = new seeds of known fault variants; unseen variants = fault "
           "phrasings never in training.", "",
           "| Split | Rules acc | Model acc | Acts on (rest escalated) | Precision when acting |",
           "| --- | --- | --- | --- | --- |"]
    for s, name in (("test", "in-distribution test"), ("heldout_test", "unseen variants")):
        m = sp[s]
        out.append(f"| {name} | {m['rules']['accuracy']:.3f} | {m['model']['accuracy']:.3f} | "
                   f"{m['model+threshold']['coverage']:.1%} | {m['model+threshold']['precision_when_acting']:.3f} |")
    out += ["", f"On unseen variants the model is right {hm['accuracy']:.0%} of the time without a threshold; "
            f"with it, it acts on {ht['coverage']:.0%} and escalates the rest. "
            "The held-out split was looked at during development; see "
            "[`ITERATIONS.md`](results/log_classifier/ITERATIONS.md).", "",
            "### Training-run doctor (tiny CPU runs)", "",
            "| Doctor | Sees | Test acc | Held-out task family acc |", "| --- | --- | --- | --- |"]
    sees = {"image": "curve picture (CNN)", "curves": "curve numbers (GBM)", "features": "curves + telemetry (GBM)",
            "ensemble": "image + features"}
    for name, d in dr["doctors"].items():
        out.append(f"| {name} | {sees[name]} | {d['test']['raw']['accuracy']:.3f} | "
                   f"{d['heldout_task']['raw']['accuracy']:.3f} |")
    bp = af["by_policy"]
    out += ["", "Auto-fix loop on harmed test + held-out-task runs (up to 3 rounds of diagnose, change setting, rerun):",
            "", "| Policy | Rescued | Rate | Healthy runs hurt |", "| --- | --- | --- | --- |"]
    for p, label in (("none", "rerun unchanged"), ("doctor", "features doctor"), ("ensemble", "ensemble doctor"),
                     ("oracle", "true-cause fix")):
        v, h = bp[p], af["healthy"][p]
        out.append(f"| {label} | {v['rescued']}/{v['harmed_runs']} | {v['rescue_rate']:.1%} | {h['hurt']}/{h['n']} |")
    out += ["", "Details: [`results/log_classifier/report.md`](results/log_classifier/report.md), "
            "[`results/doctor/report.md`](results/doctor/report.md), "
            "[`results/doctor/autofix.md`](results/doctor/autofix.md). Datasets: "
            "[`datasets/chaos-logs`](datasets/chaos-logs/README.md), "
            "[`datasets/doctor-runs`](datasets/doctor-runs/README.md).", "", END]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="labml.readme")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    path = REPO / "README.md"
    text = path.read_text(encoding="utf-8")
    i, j = text.index(START), text.index(END) + len(END)
    new = text[:i] + block() + text[j:]
    if a.check:
        return 0 if new == text else 1
    path.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
